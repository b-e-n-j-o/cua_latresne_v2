-- PPRIF Argelès : label / code_degre → R, B1–B4 s'ils matchent un zone_code corpus.
INSERT INTO corpus.alias_zonage
  (commune_insee, document_type, code_spatial, code_texte, commentaire)
SELECT DISTINCT
  '66008',
  'PPRIF',
  btrim(p.label),
  t.zone_code,
  'label spatial PPRIF → zone_code règlement'
FROM argeles.pprif p
JOIN corpus.textes t
  ON t.commune_insee = '66008'
 AND t.document_type = 'PPRIF'
 AND t.zone_code IS NOT NULL
 AND t.portee IS DISTINCT FROM 'globale'
 AND (
      upper(replace(btrim(p.label), ' ', '')) = upper(t.zone_code)
   OR upper(btrim(p.code_degre)) = upper(t.zone_code)
   OR (p.label ~* 'rouge' AND t.zone_code = 'R')
 )
WHERE p.label IS NOT NULL AND btrim(p.label) <> ''
ON CONFLICT (commune_insee, document_type, code_spatial, code_texte) DO NOTHING;

