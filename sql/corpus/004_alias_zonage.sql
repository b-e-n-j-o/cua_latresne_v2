CREATE OR REPLACE FUNCTION corpus.resoudre_codes_zonage(
  p_insee text,
  p_document_type text,
  p_codes text[]
)
RETURNS text[]
LANGUAGE sql
STABLE
AS $function$
  WITH demandes AS (
    SELECT DISTINCT btrim(c) AS code
    FROM unnest(coalesce(p_codes, ARRAY[]::text[])) AS c
    WHERE c IS NOT NULL AND btrim(c) <> ''
  ),
  via_alias AS (
    SELECT a.code_texte AS code
    FROM demandes d
    JOIN corpus.alias_zonage a
      ON a.commune_insee = p_insee
     AND a.document_type = p_document_type
     AND upper(a.code_spatial) = upper(d.code)
  ),
  sans_alias AS (
    SELECT d.code
    FROM demandes d
    WHERE NOT EXISTS (
      SELECT 1
      FROM corpus.alias_zonage a
      WHERE a.commune_insee = p_insee
        AND a.document_type = p_document_type
        AND upper(a.code_spatial) = upper(d.code)
    )
  )
  SELECT coalesce(
    array_agg(DISTINCT x.code ORDER BY x.code),
    ARRAY[]::text[]
  )
  FROM (
    SELECT code FROM via_alias
    UNION ALL
    SELECT code FROM sans_alias
  ) x;
$function$;

COMMENT ON FUNCTION corpus.resoudre_codes_zonage(text, text, text[]) IS
  'Remplace chaque code spatial par ses code_texte d''alias s''il en existe, '
  'sinon conserve le code tel quel.';
