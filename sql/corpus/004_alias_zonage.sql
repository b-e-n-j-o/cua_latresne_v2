-- 004_alias_zonage.sql
-- Lot 0.5 — codes spatiaux → codes de corpus.textes
-- Idempotent. Ne touche pas aux schémas par commune.

CREATE TABLE IF NOT EXISTS corpus.alias_zonage (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  commune_insee   text NOT NULL,
  document_type   text NOT NULL,
  code_spatial    text NOT NULL,
  code_texte      text NOT NULL,
  commentaire     text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (commune_insee, document_type, code_spatial, code_texte)
);

COMMENT ON TABLE corpus.alias_zonage IS
  'Correspondance code cartographique → zone_code de corpus.textes. '
  'Plusieurs lignes par code spatial (ex. UA → UAa et UAb).';

CREATE INDEX IF NOT EXISTS alias_zonage_lookup
  ON corpus.alias_zonage (commune_insee, document_type, upper(code_spatial));

